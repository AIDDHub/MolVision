let current = "zh";
try {
  const saved = localStorage.getItem("molviewer.lang");
  if (saved === "en" || saved === "zh") current = saved;
} catch {
  /* localStorage can be unavailable */
}

export function getLanguage() {
  return current;
}

export function setLanguage(language) {
  current = language === "en" ? "en" : "zh";
  try {
    localStorage.setItem("molviewer.lang", current);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = current === "en" ? "en" : "zh-CN";
}

export function t(text, vars = {}) {
  const template = current === "en" ? EN[text] ?? text : text;
  return String(template).replace(/\{(\w+)\}/g, (_, key) => (vars[key] ?? `{${key}}`));
}

export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((element) => {
    element.title = t(element.dataset.i18nTitle);
  });
  document.documentElement.lang = current === "en" ? "en" : "zh-CN";
}
